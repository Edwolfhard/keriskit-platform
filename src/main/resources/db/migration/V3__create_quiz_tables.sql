CREATE TABLE quiz_questions (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                question_text TEXT NOT NULL,
                                explanation TEXT NOT NULL,
                                display_order INTEGER NOT NULL UNIQUE,
                                CONSTRAINT question_order_positive CHECK (display_order > 0)
);

CREATE TABLE quiz_options (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              question_id BIGINT NOT NULL,
                              option_text TEXT NOT NULL,
                              is_correct BOOLEAN NOT NULL DEFAULT FALSE,
                              display_order INTEGER NOT NULL,
                              CONSTRAINT fk_option_question
                                  FOREIGN KEY (question_id)
                                      REFERENCES quiz_questions(id)
                                      ON DELETE CASCADE,
                              CONSTRAINT unique_option_order
                                  UNIQUE (question_id, display_order),
                              CONSTRAINT option_order_positive CHECK (display_order > 0)
);

CREATE UNIQUE INDEX one_correct_option_per_question
    ON quiz_options (question_id)
    WHERE is_correct = TRUE;